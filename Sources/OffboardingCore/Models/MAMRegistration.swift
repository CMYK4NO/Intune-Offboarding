import Foundation

/// Intune MAM / App Protection registration (`managedAppRegistration`): one app instance on one device.
///
/// A MAM registration is NOT an MDM device: a BYOD phone can have registrations and no
/// `ManagedDevice`. Never match the two by name.
///
/// API notes:
/// - List: GET /v1.0/users/{id}/managedAppRegistrations (`managedAppRegistrations` relationship of
///   the v1.0 user; delegated DeviceManagementApps.Read.All).
/// - Get one: GET /v1.0/deviceAppManagement/managedAppRegistrations/{id}.
/// - Selective wipe: v1.0 `POST /users/{id}/wipeManagedAppRegistrationsByDeviceTag` (see `MAMActionService`).
///
/// `deviceName` / `deviceTag` come from the resource type documentation but were not re-verified
/// against a live response; if a tenant omits them they decode to nil and grouping falls back to
/// the registration id.
public struct MAMRegistration: Codable, Identifiable, Hashable, Sendable {
    public let id: String
    public let userId: String?
    public let appIdentifier: MobileAppIdentifier?
    public let createdDateTime: Date?
    public let lastSyncDateTime: Date?
    public let applicationVersion: String?
    public let managementSdkVersion: String?
    public let platformVersion: String?
    public let deviceType: String?
    public let deviceName: String?
    /// Tag generated by the app management SDK; relates apps on the same device.
    public let deviceTag: String?
    /// e.g. "none", "rootedDevice".
    public let flaggedReasons: [String]?
    public let version: String?

    // Beta-only (not in the v1.0 managedAppRegistration). Filled in afterwards by `MAMDeviceDetailsProviding`,
    // used for display and for showing registrations per phone only. Never used to decide what is wiped.
    /// Entra device ID of the host device. Microsoft: may be empty even when the device is registered.
    public var azureADDeviceId: String?
    /// e.g. "iPhone18,2", "SM-A155F".
    public var deviceModel: String?
    public var deviceManufacturer: String?

    /// Polymorphic `mobileAppIdentifier`: Android uses `packageId`, iOS uses `bundleId`.
    public struct MobileAppIdentifier: Codable, Hashable, Sendable {
        public let packageId: String?
        public let bundleId: String?

        /// Human-readable app identifier, whichever platform it came from.
        public var displayValue: String? { bundleId ?? packageId }
    }

    public var isFlagged: Bool {
        (flaggedReasons ?? []).contains { $0.lowercased() != "none" }
    }
}
